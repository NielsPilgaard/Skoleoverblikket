#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Writes infrastructure/docker/docker-compose.prod.yml from the Aspire AppHost (`aspire publish`).
    Edit the AppHost (Program.cs, ProdCompose.cs), never the YAML. Dokploy deploys the committed file.
.PARAMETER Check
    Fail if the committed file differs from what the AppHost generates. CI runs this.
.EXAMPLE
    pwsh scripts/generate-prod-compose.ps1
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path $PSScriptRoot -Parent
$AppHost = Join-Path $RepoRoot 'infrastructure/aspire/Skoleoverblikket.AppHost'
$Target = Join-Path $RepoRoot 'infrastructure/docker/docker-compose.prod.yml'
$Out = Join-Path ([System.IO.Path]::GetTempPath()) "prod-compose-$([guid]::NewGuid())"

if (-not (Get-Command aspire -ErrorAction SilentlyContinue)) {
    Write-Host "aspire CLI not found. Install it: dotnet tool install --global Aspire.Cli" -ForegroundColor Red
    exit 1
}

try {
    $log = aspire publish --apphost $AppHost -o $Out --non-interactive --nologo 2>&1
    if ($LASTEXITCODE -ne 0) {
        $log | Write-Host
        Write-Host "aspire publish failed." -ForegroundColor Red
        exit 1
    }

    # Aspire's .env next to it only lists its own parameters; docs/DEPLOYMENT.md lists the real variables.
    $header = @(
        '# GENERATED by scripts/generate-prod-compose.ps1 from infrastructure/aspire/Skoleoverblikket.AppHost'
        '# (Program.cs and ProdCompose.cs). Do not edit by hand: CI fails when this file is stale.'
        '#'
        '# Production stack on the OVH VPS, deployed by Dokploy behind its Traefik. Every ${VAR} is set in'
        '# Dokploy; docs/DEPLOYMENT.md lists them. Postgres and the backup agent only start with'
        '# COMPOSE_PROFILES=selfhosted-db (task 54 cutover).'
        '#'
        '# The external volumes ARE the database. Never delete them. The backup console says which pgdata'
        '# volume is live; wal-receive holds WAL that may not be in the repo yet.'
        ''
    )
    $yaml = (Get-Content (Join-Path $Out 'docker-compose.yaml') -Raw).Replace("`r`n", "`n")
    $generated = ($header -join "`n") + $yaml

    if ($Check) {
        $committed = (Get-Content $Target -Raw).Replace("`r`n", "`n")
        if ($committed -ne $generated) {
            Write-Host "docker-compose.prod.yml is stale. Run 'pwsh scripts/generate-prod-compose.ps1' and commit it." -ForegroundColor Red
            $tmp = Join-Path $Out 'expected.yml'
            [System.IO.File]::WriteAllText($tmp, $generated)
            git --no-pager diff --no-index -- $Target $tmp
            exit 1
        }
        Write-Host "docker-compose.prod.yml is up to date." -ForegroundColor Green
    } else {
        [System.IO.File]::WriteAllText($Target, $generated)
        Write-Host "Wrote $Target" -ForegroundColor Green
    }
} finally {
    Remove-Item -Recurse -Force $Out -ErrorAction SilentlyContinue
}
